create or replace function public.current_time_bucket(p_ts timestamptz default now())
returns text
language sql
stable
as $$
  select case
    when extract(hour from p_ts at time zone 'Asia/Seoul') between 0 and 5 then '새벽'
    when extract(hour from p_ts at time zone 'Asia/Seoul') between 6 and 10 then '아침'
    when extract(hour from p_ts at time zone 'Asia/Seoul') between 11 and 16 then '낮'
    when extract(hour from p_ts at time zone 'Asia/Seoul') between 17 and 20 then '저녁'
    else '밤'
  end;
$$;

create or replace function public.upsert_daily_log(
  p_user_id uuid,
  p_log_date date,
  p_star_created boolean default false,
  p_reaction_sent boolean default false,
  p_nudge_opened boolean default false
)
returns void
language plpgsql
security definer
as $$
declare
  v_previous_streak int := 0;
begin
  select streak_count
  into v_previous_streak
  from public.daily_logs
  where user_id = p_user_id
    and log_date = p_log_date - 1;

  insert into public.daily_logs (
    user_id,
    log_date,
    star_created,
    reaction_sent,
    nudge_opened,
    streak_count
  )
  values (
    p_user_id,
    p_log_date,
    p_star_created,
    p_reaction_sent,
    p_nudge_opened,
    coalesce(v_previous_streak, 0) + 1
  )
  on conflict (user_id, log_date)
  do update set
    star_created = public.daily_logs.star_created or excluded.star_created,
    reaction_sent = public.daily_logs.reaction_sent or excluded.reaction_sent,
    nudge_opened = public.daily_logs.nudge_opened or excluded.nudge_opened,
    streak_count = greatest(public.daily_logs.streak_count, excluded.streak_count);
end;
$$;

create or replace function public.create_star(
  p_primary_tag_id bigint,
  p_secondary_tag_ids bigint[] default '{}',
  p_content text default null,
  p_visibility_status text default 'public',
  p_emotion_intensity int default 3
)
returns public.stars
language plpgsql
security definer
as $$
declare
  v_today date := (now() at time zone 'Asia/Seoul')::date;
  v_existing uuid;
  v_star public.stars;
  v_tag_id bigint;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  select id
  into v_existing
  from public.stars
  where user_id = auth.uid()
    and is_deleted = false
    and (created_at at time zone 'Asia/Seoul')::date = v_today
  limit 1;

  if v_existing is not null then
    raise exception 'Only one star per day is allowed in MVP';
  end if;

  if p_content is not null and char_length(p_content) > 80 then
    raise exception 'Star content exceeds 80 characters';
  end if;

  insert into public.stars (
    user_id,
    primary_tag_id,
    content,
    time_bucket,
    visibility_status,
    emotion_intensity
  )
  values (
    auth.uid(),
    p_primary_tag_id,
    p_content,
    public.current_time_bucket(now()),
    p_visibility_status,
    p_emotion_intensity
  )
  returning * into v_star;

  foreach v_tag_id in array p_secondary_tag_ids loop
    insert into public.star_secondary_tags (star_id, tag_id)
    values (v_star.id, v_tag_id)
    on conflict (star_id, tag_id) do nothing;
  end loop;

  perform public.upsert_daily_log(auth.uid(), v_today, true, false, false);

  return v_star;
end;
$$;

create or replace function public.get_constellation_feed(
  p_filter_name text default 'all',
  p_page_limit int default 20,
  p_page_offset int default 0
)
returns table (
  star_id uuid,
  content text,
  primary_tag_name text,
  time_bucket text,
  reaction_count int,
  relation_score int,
  created_at timestamptz
)
language sql
security definer
as $$
  with viewer_context as (
    select
      s.primary_tag_id,
      t.group_name,
      s.time_bucket
    from public.stars s
    join public.emotion_tags t on t.id = s.primary_tag_id
    where s.user_id = auth.uid()
      and s.is_deleted = false
    order by s.created_at desc
    limit 1
  )
  select
    s.id as star_id,
    s.content,
    t.name_ko as primary_tag_name,
    s.time_bucket,
    s.reaction_count,
    (
      case when exists (
        select 1
        from viewer_context vc
        where vc.primary_tag_id = s.primary_tag_id
      ) then 40 else 0 end
      +
      case when exists (
        select 1
        from viewer_context vc
        where vc.group_name = t.group_name
      ) then 20 else 0 end
      +
      case when exists (
        select 1
        from viewer_context vc
        where vc.time_bucket = s.time_bucket
      ) then 15 else 0 end
      +
      case when s.created_at >= now() - interval '24 hours' then 10 else 0 end
      +
      case when not exists (
        select 1
        from public.star_views sv
        where sv.viewer_user_id = auth.uid()
          and sv.star_id = s.id
      ) then 15 else 0 end
      +
      case when s.reaction_count >= 5 then -20 else 0 end
      +
      case when s.user_id = auth.uid() then -30 else 0 end
    )::int as relation_score,
    s.created_at
  from public.stars s
  join public.emotion_tags t on t.id = s.primary_tag_id
  where s.is_deleted = false
    and s.visibility_status = 'public'
    and s.user_id <> auth.uid()
    and not exists (
      select 1 from public.blocks b
      where (b.blocker_user_id = auth.uid() and b.blocked_user_id = s.user_id)
         or (b.blocker_user_id = s.user_id and b.blocked_user_id = auth.uid())
    )
    and not exists (
      select 1
      from public.star_views sv
      where sv.viewer_user_id = auth.uid()
        and sv.star_id = s.id
    )
    and (
      p_filter_name = 'all'
      or (p_filter_name = 'similar' and exists (
        select 1
        from viewer_context vc
        where vc.primary_tag_id = s.primary_tag_id or vc.group_name = t.group_name
      ))
      or (p_filter_name = 'night' and s.time_bucket = '밤')
    )
  order by relation_score desc, s.created_at desc
  limit p_page_limit
  offset p_page_offset;
$$;

create or replace function public.send_reaction(
  p_star_id uuid,
  p_reaction_type_id bigint
)
returns public.reactions
language plpgsql
security definer
as $$
declare
  v_today date := (now() at time zone 'Asia/Seoul')::date;
  v_target_star public.stars;
  v_reaction public.reactions;
  v_count int;
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;

  select *
  into v_target_star
  from public.stars
  where id = p_star_id
    and is_deleted = false;

  if not found then
    raise exception 'Star not found';
  end if;

  if v_target_star.user_id = auth.uid() then
    raise exception 'Self reaction is not allowed';
  end if;

  if exists (
    select 1 from public.blocks b
    where (b.blocker_user_id = auth.uid() and b.blocked_user_id = v_target_star.user_id)
       or (b.blocker_user_id = v_target_star.user_id and b.blocked_user_id = auth.uid())
  ) then
    raise exception 'Blocked relationship';
  end if;

  select count(*)
  into v_count
  from public.reactions r
  where r.sender_user_id = auth.uid()
    and (r.created_at at time zone 'Asia/Seoul')::date = v_today;

  if v_count >= 40 then
    raise exception 'Daily reaction cap exceeded';
  end if;

  insert into public.reactions (
    star_id,
    sender_user_id,
    reaction_type_id
  )
  values (
    p_star_id,
    auth.uid(),
    p_reaction_type_id
  )
  returning * into v_reaction;

  update public.stars
  set reaction_count = reaction_count + 1
  where id = p_star_id;

  insert into public.nudges (
    user_id,
    type,
    title,
    body,
    delivered_at
  )
  values (
    v_target_star.user_id,
    'reaction_received',
    '따뜻한 반응이 도착했어요',
    '누군가 당신의 별을 다정하게 바라봤어요.',
    now()
  );

  perform public.upsert_daily_log(auth.uid(), v_today, false, true, false);

  return v_reaction;
end;
$$;

