create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  nickname text not null unique,
  avatar_type text not null default 'glow',
  push_token text,
  timezone text not null default 'Asia/Seoul',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.emotion_tags (
  id bigint generated by default as identity primary key,
  name_ko text not null unique,
  group_name text not null,
  priority int not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.stars (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  primary_tag_id bigint not null references public.emotion_tags(id),
  content varchar(80),
  time_bucket text not null check (time_bucket in ('새벽', '아침', '낮', '저녁', '밤')),
  emotion_intensity int not null default 3 check (emotion_intensity between 1 and 5),
  visibility_status text not null default 'public' check (visibility_status in ('public', 'limited', 'private')),
  reaction_count int not null default 0,
  is_deleted boolean not null default false,
  created_at timestamptz not null default now(),
  expires_at timestamptz
);

create table if not exists public.star_secondary_tags (
  id uuid primary key default gen_random_uuid(),
  star_id uuid not null references public.stars(id) on delete cascade,
  tag_id bigint not null references public.emotion_tags(id),
  unique (star_id, tag_id)
);

create table if not exists public.reaction_types (
  id bigint generated by default as identity primary key,
  code text not null unique,
  label_ko text not null,
  icon text not null,
  is_active boolean not null default true
);

create table if not exists public.reactions (
  id uuid primary key default gen_random_uuid(),
  star_id uuid not null references public.stars(id) on delete cascade,
  sender_user_id uuid not null references auth.users(id) on delete cascade,
  reaction_type_id bigint not null references public.reaction_types(id),
  created_at timestamptz not null default now(),
  unique (star_id, sender_user_id)
);

create table if not exists public.nudges (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null,
  title text not null,
  body text not null,
  delivered_at timestamptz,
  opened_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.daily_logs (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  log_date date not null,
  star_created boolean not null default false,
  reaction_sent boolean not null default false,
  nudge_opened boolean not null default false,
  streak_count int not null default 0,
  unique (user_id, log_date)
);

create table if not exists public.blocks (
  id uuid primary key default gen_random_uuid(),
  blocker_user_id uuid not null references auth.users(id) on delete cascade,
  blocked_user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (blocker_user_id, blocked_user_id),
  check (blocker_user_id <> blocked_user_id)
);

create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  reporter_user_id uuid not null references auth.users(id) on delete cascade,
  target_star_id uuid not null references public.stars(id) on delete cascade,
  reason text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.star_views (
  id uuid primary key default gen_random_uuid(),
  viewer_user_id uuid not null references auth.users(id) on delete cascade,
  star_id uuid not null references public.stars(id) on delete cascade,
  seen_at timestamptz not null default now(),
  unique (viewer_user_id, star_id)
);

create index if not exists stars_user_created_at_idx on public.stars (user_id, created_at desc);
